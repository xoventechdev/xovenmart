// One-shot helper that generates every secret/env var the n8n service
// needs and writes them to .env.n8n.local (gitignored) plus prints them
// to stdout so they can be pasted into the VPS .env.
//
// Run with `node tools/generate-n8n-secrets.mjs` from the repo root.
// The output file is safe to keep locally — it must NEVER be committed
// and the .gitignore already excludes .env.local / .env.*.local.

import { randomBytes } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve as pathResolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
// Resolve bcryptjs from inside the api workspace so we don't need a
// workspace-wide dep just for this one-off script.
const bcrypt = require('../apps/api/node_modules/bcryptjs');

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = pathResolve(__dirname, '..');
const OUT_PATH = join(REPO_ROOT, '.env.n8n.local');

function base64(bytes) {
  return randomBytes(bytes).toString('base64');
}
function hex(bytes) {
  return randomBytes(bytes).toString('hex');
}

const secrets = {
  N8N_DB_PASSWORD:         base64(24),                  // 24 random bytes → base64 (~32 chars)
  N8N_ENCRYPTION_KEY:      hex(32),                     // 64 hex chars
  N8N_BOT_SERVICE_TOKEN:   hex(32),                     // 64 hex chars
  N8N_INGEST_SECRET:       hex(32),                     // 64 hex chars
  META_VERIFY_TOKEN:       hex(24),                     // 48 hex chars
  N8N_ADMIN_USER:          'admin',
};

// The plaintext we hash for N8N_ADMIN_PASSWORD. The plaintext is what
// the operator types into the browser; only the hash gets baked into
// Caddy / committed. We keep the plaintext in the local-only file so
// the operator can copy-paste it on first login.
const N8N_ADMIN_PASSWORD_PLAINTEXT = base64(18); // ~24 chars, easy to type
// Caddy's hash-password defaults to cost=14 bcrypt; bcryptjs default
// cost is also 10, so we explicitly set 14 to match what
// `docker run --rm caddy:2-alpine caddy hash-password` produces.
secrets.N8N_ADMIN_PASSWORD = N8N_ADMIN_PASSWORD_PLAINTEXT;
secrets.N8N_ADMIN_PASSWORD_HASHED = bcrypt.hashSync(N8N_ADMIN_PASSWORD_PLAINTEXT, 14);

const banner = '# Generated by tools/generate-n8n-secrets.mjs on ' + new Date().toISOString() + '\n' +
               '# DO NOT COMMIT THIS FILE. Safe to copy values into VPS .env.\n';
const body = Object.entries(secrets)
  .map(([k, v]) => `${k}=${v}`)
  .join('\n') + '\n';

writeFileSync(OUT_PATH, banner + body, { mode: 0o600 });
console.log(`# Wrote ${secrets.length} values to ${OUT_PATH}\n`);
console.log(banner + body);
